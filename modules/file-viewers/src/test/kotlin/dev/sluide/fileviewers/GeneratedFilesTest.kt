package dev.sluide.fileviewers

import java.nio.file.Path
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class GeneratedFilesTest {
    @Test
    fun `lock files are known by their exact name, in any case`() {
        val expected =
            mapOf(
                "uv.lock" to GeneratedFile("uv", "pyproject.toml", "uv lock"),
                "poetry.lock" to GeneratedFile("Poetry", "pyproject.toml", "poetry lock"),
                "pdm.lock" to GeneratedFile("PDM", "pyproject.toml", "pdm lock"),
                "Pipfile.lock" to GeneratedFile("Pipenv", "Pipfile", "pipenv lock"),
                "Cargo.lock" to GeneratedFile("Cargo", "Cargo.toml", "cargo update"),
                "package-lock.json" to GeneratedFile("npm", "package.json", "npm install"),
                "yarn.lock" to GeneratedFile("Yarn", "package.json", "yarn install"),
                "pnpm-lock.yaml" to GeneratedFile("pnpm", "package.json", "pnpm install"),
                "Gemfile.lock" to GeneratedFile("Bundler", "Gemfile", "bundle install"),
                "composer.lock" to GeneratedFile("Composer", "composer.json", "composer update"),
            )
        for ((name, file) in expected) {
            assertEquals(file, GeneratedFiles.of(Path.of("project", name)), name)
            assertEquals(file, GeneratedFiles.of(Path.of(name.uppercase())), name.uppercase())
        }
    }

    @Test
    fun `other files, also with similar names, are not generated`() {
        for (name in listOf("pyproject.toml", "Pipfile", "Cargo.toml", "package.json", "my-uv.lock", "uv.lock.bak")) {
            assertNull(GeneratedFiles.of(Path.of(name)), name)
        }
        assertNull(GeneratedFiles.of(Path.of("/")), "no file name")
    }

    @Test
    fun `the message names the file, the tool, its source and the command`() {
        assertEquals(
            "UV.lock is generated by uv from pyproject.toml; change that file and run \"uv lock\" instead of " +
                "editing this one.",
            GeneratedFiles.of(Path.of("UV.lock"))?.message("UV.lock"),
        )
    }
}
