#!/usr/bin/env bash
# Regenerates the Opus-MT model catalog (ADR 0126) from Hugging Face: every Xenova/opus-mt-<src>-<tgt> repo with a
# single source and target language, pinned to its current commit. Per pair it lists the shared files (tokenizer and
# configs) and the encoder and merged decoder for Medium (int8, *_quantized) and High (fp32).
# Sizes and sha256 of the ONNX files come from the API (Git LFS ids); the small shared files are downloaded and hashed.
#
# Usage: modules/translation/scripts/generate-opus-mt-catalog.sh [output.tsv]
# Needs curl, jq, sha256sum and access to huggingface.co. Review the diff before committing: a changed commit means
# changed model files.
set -euo pipefail

out=${1:-"$(dirname "$0")/../src/main/resources/dev/sluide/translation/opus-mt-catalog.tsv"}
api=https://huggingface.co/api/models
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Repos left out: language groups (ROMANCE, bat, mul, gem, gmw) need target-language tokens; "jap" is the Bible-only
# Japanese corpus (ja-en covers Japanese as a source); tc-big-tr-en duplicates tr-en at twice the size. The app offers
# the languages with a model to or from English, so no-de and ro-fr (no no-en, no ro-en) could never be chosen.
skip='^(.*-(ROMANCE|bat|mul|gem|gmw)|(ROMANCE|bat|mul|gem|gmw)-.*|.*jap.*|tc-big-.*|no-de|ro-fr)$'

curl -sfL "$api?author=Xenova&search=opus-mt-&limit=1000" | jq -r '.[].id' | sort > "$work/repos"

{
  echo "# Opus-MT ONNX models (Xenova conversions of Helsinki-NLP/opus-mt-*), CC-BY 4.0."
  echo "# Generated by modules/translation/scripts/generate-opus-mt-catalog.sh; do not edit by hand."
  echo "# pair	quality	path	url	bytes	sha256"
} > "$work/catalog"

while read -r repo; do
  pair=${repo#Xenova/opus-mt-}
  if [[ $pair =~ $skip ]]; then
    echo "skip $repo (left out, see above)" >&2
    continue
  fi
  commit=$(curl -sfL "$api/$repo" | jq -r .sha)
  curl -sfL "$api/$repo/tree/$commit/onnx?expand=true" > "$work/onnx.json"
  base="https://huggingface.co/$repo/resolve/$commit"
  rows=()
  missing=""
  for spec in "medium encoder onnx/encoder_model_quantized.onnx" "medium decoder onnx/decoder_model_merged_quantized.onnx" \
              "high encoder onnx/encoder_model.onnx" "high decoder onnx/decoder_model_merged.onnx"; do
    read -r quality name file <<< "$spec"
    entry=$(jq -r --arg p "$file" '.[] | select(.path == $p) | "\(.size)\t\(.lfs.oid)"' "$work/onnx.json")
    if [[ -z $entry ]]; then
      missing="$missing $file"
      continue
    fi
    rows+=("$pair	$quality	$quality/$name.onnx	$base/$file	$entry")
  done
  if [[ -n $missing ]]; then
    echo "skip $repo (missing$missing)" >&2
    continue
  fi
  for file in tokenizer.json config.json generation_config.json; do
    curl -sfL -o "$work/$file" "$base/$file"
    rows+=("$pair	shared	$file	$base/$file	$(stat -c %s "$work/$file")	$(sha256sum "$work/$file" | cut -d' ' -f1)")
  done
  model=$(jq -r .model.type "$work/tokenizer.json")
  separate=$(curl -sfL "$base/tokenizer_config.json" | jq -r '.separate_vocabs // false')
  if [[ $model != Unigram || $separate != false ]]; then
    echo "skip $repo (tokenizer $model, separate vocabs $separate)" >&2
    continue
  fi
  printf '%s\n' "${rows[@]}" >> "$work/catalog"
  echo "ok   $repo @ $commit" >&2
done < "$work/repos"

mv "$work/catalog" "$out"
echo "wrote $out" >&2
