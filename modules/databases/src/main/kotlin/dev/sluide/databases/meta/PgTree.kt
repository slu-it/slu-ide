package dev.sluide.databases.meta

/** The row sets of one PostgreSQL schema (see [PgQueries]); shared by the tree and the table DDL. */
internal class PgSchemaRows(
    val relations: List<Row> = emptyList(),
    val columns: List<Row> = emptyList(),
    val constraints: List<Row> = emptyList(),
    val indexes: List<Row> = emptyList(),
    val triggers: List<Row> = emptyList(),
    val routines: List<Row> = emptyList(),
    val types: List<Row> = emptyList(),
)

/** "integer not null default 0": the muted text after a column's name. */
internal fun pgColumnDetail(row: Row): String =
    buildList {
        add(row.text("type"))
        if (row.flag("notnull")) add("not null")
        pgColumnDefault(row)?.let { add(it) }
    }.joinToString(" ")

private fun pgColumnDefault(row: Row): String? {
    val dflt = row.str("dflt")
    return when {
        row.text("generated") == "s" && dflt != null -> "generated always as ($dflt)"
        row.text("identity") == "a" -> "generated always as identity"
        row.text("identity") == "d" -> "generated by default as identity"
        dflt != null -> "default $dflt"
        else -> null
    }
}

private fun pgConstraintNode(
    schema: String,
    row: Row,
): DbObject {
    val kind =
        when (row.text("type")) {
            "p" -> ObjectKind.PRIMARY_KEY
            "u" -> ObjectKind.UNIQUE
            "f" -> ObjectKind.FOREIGN_KEY
            else -> ObjectKind.CHECK
        }
    val detail =
        when (kind) {
            ObjectKind.FOREIGN_KEY -> {
                "(${row.text("cols")}) → ${row.text("fschema")}.${row.text("ftable")}(${row.text("fcols")})"
            }

            ObjectKind.CHECK -> {
                row.text("def")
            }

            else -> {
                "(${row.text("cols")})"
            }
        }
    return DbObject(kind, schema, row.text("name"), row.text("tbl"), detail)
}

private val triggerTiming = Regex("""(BEFORE|AFTER|INSTEAD OF) (.*?) ON """)

private fun pgTriggerDetail(def: String): String =
    triggerTiming.find(def)?.let { "${it.groupValues[1]} ${it.groupValues[2]}".lowercase() }.orEmpty()

private fun pgTypeNode(
    schema: String,
    row: Row,
): DbObject {
    val kind =
        when (row.text("kind")) {
            "e" -> ObjectKind.ENUM
            "d" -> ObjectKind.DOMAIN
            else -> ObjectKind.COMPOSITE_TYPE
        }
    return DbObject(kind, schema, row.text("name"), detail = row.text("detail"))
}

private fun pgRoutineNode(
    schema: String,
    row: Row,
): DbObject =
    DbObject(
        if (row.text("kind") == "p") ObjectKind.PROCEDURE else ObjectKind.FUNCTION,
        schema,
        row.text("name"),
        detail = routineDetail(row.text("types"), row.str("result")),
        ref = row.text("ident"),
    )

/** The group nodes of a PostgreSQL schema from its catalog rows. */
internal fun pgSchemaTree(
    schema: String,
    rows: PgSchemaRows,
): List<DbObject> {
    val relations =
        rows.relations.map {
            val kind =
                when (it.text("kind")) {
                    "v" -> ObjectKind.VIEW
                    "m" -> ObjectKind.MATERIALIZED_VIEW
                    "S" -> ObjectKind.SEQUENCE
                    else -> ObjectKind.TABLE
                }
            DbObject(kind, schema, it.text("name"))
        }
    val columns =
        rows.columns.map {
            DbObject(ObjectKind.COLUMN, schema, it.text("name"), it.text("tbl"), pgColumnDetail(it))
        }
    val indexes =
        rows.indexes.map {
            DbObject(
                ObjectKind.INDEX,
                schema,
                it.text("name"),
                it.text("tbl"),
                "(${it.text("cols")})" + if (it.flag("uniq")) " unique" else "",
            )
        }
    val triggers =
        rows.triggers.map {
            DbObject(ObjectKind.TRIGGER, schema, it.text("name"), it.text("tbl"), pgTriggerDetail(it.text("def")))
        }
    return buildSchemaTree(
        schema,
        SchemaLeaves(
            relations = relations,
            columns = columns,
            tableObjects = rows.constraints.map { pgConstraintNode(schema, it) } + indexes + triggers,
            routines = rows.routines.map { pgRoutineNode(schema, it) },
            types = rows.types.map { pgTypeNode(schema, it) },
        ),
    )
}
