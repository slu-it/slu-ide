package dev.sluide.databases.meta

/** The row sets of one PostgreSQL schema (see [PgQueries]); shared by the tree and the table DDL. */
internal class PgSchemaRows(
    val relations: List<Row> = emptyList(),
    val columns: List<Row> = emptyList(),
    val constraints: List<Row> = emptyList(),
    val indexes: List<Row> = emptyList(),
    val triggers: List<Row> = emptyList(),
    val ownedSequences: List<Row> = emptyList(),
    val routines: List<Row> = emptyList(),
    val types: List<Row> = emptyList(),
)

/** "integer not null default 0": the muted text after a column's name. */
internal fun pgColumnDetail(row: Row): String =
    buildList {
        add(row.text("type"))
        if (row.flag("notnull")) add("not null")
        pgColumnDefault(row)?.let { add(it) }
    }.joinToString(" ")

private fun pgColumnDefault(row: Row): String? {
    val dflt = row.str("dflt")
    return when {
        row.text("generated") == "s" && dflt != null -> "generated always as ($dflt)"
        row.text("generated") == "v" && dflt != null -> "generated always as ($dflt) virtual"
        row.text("identity") == "a" -> "generated always as identity"
        row.text("identity") == "d" -> "generated by default as identity"
        dflt != null -> "default $dflt"
        else -> null
    }
}

private fun pgConstraintNode(
    schema: String,
    row: Row,
): DbObject {
    val kind =
        when (row.text("type")) {
            "p" -> ObjectKind.PRIMARY_KEY

            // An exclusion constraint is shown as a unique-like key whose detail is its definition.
            "u", "x" -> ObjectKind.UNIQUE

            "f" -> ObjectKind.FOREIGN_KEY

            else -> ObjectKind.CHECK
        }
    val detail =
        when (kind) {
            ObjectKind.FOREIGN_KEY -> {
                "(${row.text("cols")}) → ${row.text("fschema")}.${row.text("ftable")}(${row.text("fcols")})"
            }

            ObjectKind.CHECK -> {
                row.text("def")
            }

            else -> {
                if (row.text("type") == "x") row.text("def") else "(${row.text("cols")})"
            }
        }
    return DbObject(kind, schema, row.text("name"), row.text("tbl"), detail)
}

/** "before insert or update": timing and events from the `tgtype` bit mask (2 before, 64 instead of, 4/16/8/32 events). */
internal fun pgTriggerDetail(tgtype: Int): String {
    val timing =
        when {
            tgtype and 64 != 0 -> "instead of"
            tgtype and 2 != 0 -> "before"
            else -> "after"
        }
    val events =
        listOf(4 to "insert", 16 to "update", 8 to "delete", 32 to "truncate").filter { tgtype and it.first != 0 }
    return "$timing ${events.joinToString(" or ") { it.second }}".trim()
}

private fun pgTypeNode(
    schema: String,
    row: Row,
): DbObject {
    val kind =
        when (row.text("kind")) {
            "e" -> ObjectKind.ENUM
            "d" -> ObjectKind.DOMAIN
            else -> ObjectKind.COMPOSITE_TYPE
        }
    return DbObject(kind, schema, row.text("name"), detail = row.text("detail"))
}

private fun pgRoutineNode(
    schema: String,
    row: Row,
): DbObject =
    DbObject(
        if (row.text("kind") == "p") ObjectKind.PROCEDURE else ObjectKind.FUNCTION,
        schema,
        row.text("name"),
        detail = routineDetail(row.text("types"), row.str("result")),
        ref = row.text("ident"),
    )

/** The group nodes of a PostgreSQL schema from its catalog rows. */
internal fun pgSchemaTree(
    schema: String,
    rows: PgSchemaRows,
): List<DbObject> {
    val relations =
        rows.relations.map {
            val kind =
                when (it.text("kind")) {
                    "v" -> ObjectKind.VIEW
                    "m" -> ObjectKind.MATERIALIZED_VIEW
                    "S" -> ObjectKind.SEQUENCE
                    else -> ObjectKind.TABLE
                }
            val detail =
                when {
                    it.flag("ispart") -> it.text("bound")
                    it.str("partkey") != null -> it.text("partkey")
                    it.str("fserver") != null -> "foreign, server ${it.text("fserver")}"
                    else -> ""
                }
            DbObject(kind, schema, it.text("name"), detail = detail)
        }
    // A partition is nested under its parent when both are in this schema.
    val names = rows.relations.map { it.text("name") }.toSet()
    val partitionParents =
        rows.relations
            .filter { it.flag("ispart") && it.text("pschema") == schema && it.text("parent") in names }
            .associate { it.text("name") to it.text("parent") }
    val columns =
        rows.columns.map {
            DbObject(ObjectKind.COLUMN, schema, it.text("name"), it.text("tbl"), pgColumnDetail(it))
        }
    val indexes =
        rows.indexes.map {
            DbObject(
                ObjectKind.INDEX,
                schema,
                it.text("name"),
                it.text("tbl"),
                "(${it.text("cols")})" + if (it.flag("uniq")) " unique" else "",
            )
        }
    val triggers =
        rows.triggers.map {
            DbObject(ObjectKind.TRIGGER, schema, it.text("name"), it.text("tbl"), pgTriggerDetail(it.int("tgtype")))
        }
    return buildSchemaTree(
        schema,
        SchemaLeaves(
            relations = relations,
            partitionParents = partitionParents,
            columns = columns,
            tableObjects = rows.constraints.map { pgConstraintNode(schema, it) } + indexes + triggers,
            routines = rows.routines.map { pgRoutineNode(schema, it) },
            types = rows.types.map { pgTypeNode(schema, it) },
        ),
    )
}
