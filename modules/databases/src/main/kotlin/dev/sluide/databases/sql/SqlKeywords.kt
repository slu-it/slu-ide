package dev.sluide.databases.sql

import dev.sluide.databases.connect.DatabaseKind

object SqlKeywords {
    private val COMMON =
        (
            "ADD ALL ALTER ANALYZE AND ANY AS ASC BEGIN BETWEEN BY CASE CAST CHECK " +
                "COLUMN COMMIT CONSTRAINT COUNT CREATE CROSS CURRENT_DATE " +
                "CURRENT_TIMESTAMP DATABASE DEFAULT DELETE DESC DESCRIBE DISTINCT DROP " +
                "ELSE END EXCEPT EXISTS EXPLAIN FALSE FETCH FOREIGN FROM FULL GRANT " +
                "GROUP HAVING IN INDEX INNER INSERT INTERSECT INTO IS JOIN KEY LEFT " +
                "LIKE LIMIT NATURAL NOT NULL OFFSET ON OR ORDER OUTER PRIMARY " +
                "REFERENCES RIGHT ROLLBACK SCHEMA SELECT SET SHOW TABLE THEN TRUE " +
                "TRUNCATE UNION UNIQUE UPDATE USING VALUES VIEW WHEN WHERE WITH"
        ).split(' ')

    private val POSTGRESQL =
        (
            "RETURNING ILIKE OVER PARTITION WINDOW LATERAL RECURSIVE MATERIALIZED " +
                "CONFLICT DO NOTHING SIMILAR TO SERIAL BIGSERIAL TEXT JSONB VACUUM ONLY " +
                "FILTER NULLS FIRST LAST"
        ).split(' ')

    private val MARIADB =
        (
            "REPLACE DUPLICATE STRAIGHT_JOIN DESCRIBE ENGINE AUTO_INCREMENT " +
                "UNSIGNED REGEXP RLIKE IGNORE USE TINYINT MEDIUMINT DATETIME SHOW LOCK " +
                "UNLOCK RETURNING OVER PARTITION"
        ).split(' ')

    /** Words that need quoting as identifiers, lowercase: PostgreSQL's reserved words and MariaDB's common ones. */
    internal val RESERVED: Set<String> =
        (
            "ALL ANALYSE ANALYZE AND ANY ARRAY AS ASC ASYMMETRIC BETWEEN BOTH BY CASE CAST CHECK COLLATE " +
                "COLUMN CONSTRAINT CREATE CROSS CURRENT_CATALOG CURRENT_DATE CURRENT_ROLE CURRENT_TIME " +
                "CURRENT_TIMESTAMP CURRENT_USER DEFAULT DEFERRABLE DELETE DESC DISTINCT DO DROP ELSE END " +
                "EXCEPT FALSE FETCH FOR FOREIGN FROM FULL GRANT GROUP HAVING IN INDEX INITIALLY INNER INSERT " +
                "INTERSECT INTO IS JOIN KEY LATERAL LEADING LEFT LIKE LIMIT LOCALTIME LOCALTIMESTAMP NATURAL " +
                "NOT NULL OFFSET ON ONLY OR ORDER OUTER PLACING PRIMARY REFERENCES RETURNING RIGHT SELECT " +
                "SESSION_USER SET SOME SYMMETRIC SYSTEM_USER TABLE THEN TO TRAILING TRUE UNION UNIQUE UPDATE " +
                "USER USING VALUES VARIADIC WHEN WHERE WINDOW WITH"
        ).split(' ').map { it.lowercase() }.toSet()

    /** Common SQL keywords plus the ones of [kind] (`RETURNING`, `ILIKE`, ... / `LIMIT`, `REPLACE`, ...), sorted, uppercase. */
    fun all(kind: DatabaseKind): List<String> =
        (COMMON + if (kind == DatabaseKind.MARIADB) MARIADB else POSTGRESQL).distinct().sorted()
}
