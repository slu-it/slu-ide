package dev.sluide.databases.meta

import dev.sluide.databases.connect.DatabaseKind
import dev.sluide.databases.sql.SqlNames

private fun q(name: String) = SqlNames.quote(DatabaseKind.POSTGRESQL, name)

private fun qualified(
    schema: String?,
    name: String,
) = SqlNames.qualified(DatabaseKind.POSTGRESQL, schema, name)

/** One column as it appears in `CREATE TABLE`: `"name" type [generated…|default …] [not null]`. */
internal fun pgColumnLine(row: Row): String {
    val dflt = row.str("dflt")
    val tail =
        when {
            row.text("generated") == "s" && dflt != null -> " GENERATED ALWAYS AS ($dflt) STORED"
            row.text("generated") == "v" && dflt != null -> " GENERATED ALWAYS AS ($dflt)"
            row.text("identity") == "a" -> " GENERATED ALWAYS AS IDENTITY"
            row.text("identity") == "d" -> " GENERATED BY DEFAULT AS IDENTITY"
            dflt != null -> " DEFAULT $dflt"
            else -> ""
        }
    return "${q(row.text("name"))} ${row.text("type")}$tail" + if (row.flag("notnull")) " NOT NULL" else ""
}

private fun constraintClause(row: Row) = "CONSTRAINT ${q(row.text("name"))} ${row.text("def")}"

private fun indexDefs(
    table: String,
    rows: PgSchemaRows,
): List<String> = rows.indexes.filter { it.text("tbl") == table && !it.flag("backs") }.map { it.text("def") }

/**
 * The DDL of a table: the sequences its columns own, `CREATE TABLE` (a partitioned table with `PARTITION BY`, a
 * partition as `PARTITION OF` its parent, a foreign table as `CREATE FOREIGN TABLE … SERVER`), `ALTER SEQUENCE …
 * OWNED BY`, then `CREATE INDEX` for indexes that back no constraint and the triggers. A partition leaves out what
 * its parent's indexes, triggers and constraints give it. Empty when the table is gone.
 */
internal fun pgTableDdl(
    schema: String,
    table: String,
    rows: PgSchemaRows,
): String {
    val rel = rows.relations.firstOrNull { it.text("name") == table } ?: return ""
    val name = qualified(schema, table)
    val partition = rel.flag("ispart")
    val partKey = rel.str("partkey")?.let { "\nPARTITION BY $it" }.orEmpty()
    val create =
        if (partition) {
            val parent = qualified(rel.str("pschema"), rel.text("parent"))
            "CREATE TABLE $name PARTITION OF $parent ${rel.text("bound")}$partKey"
        } else {
            val lines =
                rows.columns.filter { it.text("tbl") == table }.map { pgColumnLine(it) } +
                    rows.constraints.filter { it.text("tbl") == table }.map { constraintClause(it) }
            val body = if (lines.isEmpty()) "()" else "(\n" + lines.joinToString(",\n") { "    $it" } + "\n)"
            val foreign = rel.text("kind") == "f"
            val tail =
                if (foreign) {
                    "\nSERVER ${q(rel.text("fserver"))}" + rel.str("foptions")?.let { "\nOPTIONS ($it)" }.orEmpty()
                } else {
                    partKey
                }
            "CREATE ${if (foreign) "FOREIGN TABLE" else "TABLE"} $name $body$tail"
        }
    val owned = if (partition) emptyList() else rows.ownedSequences.filter { it.text("tbl") == table }
    val sequences = owned.map { pgSequenceDdl(it.text("seqschema"), it.text("seq"), it) }
    val ownedBy =
        owned.map {
            "ALTER SEQUENCE ${qualified(it.text("seqschema"), it.text("seq"))} OWNED BY $name.${q(it.text("col"))}"
        }
    val indexes = if (partition) emptyList() else indexDefs(table, rows)
    val triggers =
        if (partition) emptyList() else rows.triggers.filter { it.text("tbl") == table }.map { it.text("def") }
    return (sequences + create + ownedBy + indexes + triggers).joinToString("\n") { withSemicolon(it) }
}

/** The DDL of a column, key, index, check or trigger [obj] from the table's rows; `null` for other kinds. */
internal fun pgTableChildDdl(
    obj: DbObject,
    rows: PgSchemaRows,
): String? {
    val table = obj.table ?: return null

    fun row(list: List<Row>) = list.firstOrNull { it.text("tbl") == table && it.text("name") == obj.name }
    return when (obj.kind) {
        ObjectKind.COLUMN -> {
            row(rows.columns)?.let {
                withSemicolon("ALTER TABLE ${qualified(obj.schema, table)} ADD COLUMN ${pgColumnLine(it)}")
            }
        }

        ObjectKind.PRIMARY_KEY, ObjectKind.UNIQUE, ObjectKind.FOREIGN_KEY, ObjectKind.CHECK -> {
            row(rows.constraints)?.let {
                withSemicolon("ALTER TABLE ${qualified(obj.schema, table)} ADD ${constraintClause(it)}")
            }
        }

        ObjectKind.INDEX -> {
            row(rows.indexes)?.let { withSemicolon(it.text("def")) }
        }

        ObjectKind.TRIGGER -> {
            row(rows.triggers)?.let { withSemicolon(it.text("def")) }
        }

        else -> {
            null
        }
    }
}

/** `CREATE OR REPLACE VIEW`, or for a materialized view `CREATE MATERIALIZED VIEW` and its indexes; empty when gone. */
internal fun pgViewDdl(
    obj: DbObject,
    definition: String,
    rows: PgSchemaRows = PgSchemaRows(),
): String {
    if (definition.isBlank()) return ""
    val materialized = obj.kind == ObjectKind.MATERIALIZED_VIEW
    val head = if (materialized) "CREATE MATERIALIZED VIEW" else "CREATE OR REPLACE VIEW"
    val tail = if (materialized) "\nWITH DATA" else ""
    val create = "$head ${qualified(obj.schema, obj.name)} AS\n${definition.trim().trimEnd(';')}$tail"
    val indexes = if (materialized) indexDefs(obj.name, rows) else emptyList()
    return (listOf(create) + indexes).joinToString("\n") { withSemicolon(it) }
}

internal fun pgSequenceDdl(
    schema: String?,
    name: String,
    row: Row,
): String =
    withSemicolon(
        "CREATE SEQUENCE ${qualified(schema, name)}\n" +
            "    AS ${row.text("type")}\n" +
            "    START WITH ${row.text("start_value")}\n" +
            "    INCREMENT BY ${row.text("increment_by")}\n" +
            "    MINVALUE ${row.text("min_value")}\n" +
            "    MAXVALUE ${row.text("max_value")}\n" +
            "    CACHE ${row.text("cache_size")}\n" +
            "    " + if (row.flag("cycle")) "CYCLE" else "NO CYCLE",
    )

/** [quotedLabels] are already SQL literals (`quote_literal`). */
internal fun pgEnumDdl(
    obj: DbObject,
    quotedLabels: List<String>,
): String =
    if (quotedLabels.isEmpty()) {
        ""
    } else {
        withSemicolon("CREATE TYPE ${qualified(obj.schema, obj.name)} AS ENUM (${quotedLabels.joinToString(", ")})")
    }

internal fun pgDomainDdl(
    obj: DbObject,
    domain: Row?,
    constraints: List<Row>,
): String {
    if (domain == null) return ""
    val parts =
        buildList {
            add("CREATE DOMAIN ${qualified(obj.schema, obj.name)} AS ${domain.text("base")}")
            domain.str("dflt")?.let { add("DEFAULT $it") }
            if (domain.flag("notnull")) add("NOT NULL")
            constraints.forEach { add(constraintClause(it)) }
        }
    return withSemicolon(parts.joinToString("\n    "))
}

internal fun pgCompositeDdl(
    obj: DbObject,
    attributes: List<Row>,
): String =
    if (attributes.isEmpty()) {
        ""
    } else {
        withSemicolon(
            "CREATE TYPE ${qualified(obj.schema, obj.name)} AS (\n" +
                attributes.joinToString(",\n") { "    ${q(it.text("name"))} ${it.text("type")}" } + "\n)",
        )
    }
