package dev.sluide.databases.meta

import dev.sluide.databases.connect.DatabaseKind
import dev.sluide.databases.sql.SqlNames

private fun q(name: String) = SqlNames.quote(DatabaseKind.POSTGRESQL, name)

private fun qualified(
    schema: String?,
    name: String,
) = SqlNames.qualified(DatabaseKind.POSTGRESQL, schema, name)

private fun literal(value: String) = "'" + value.replace("'", "''") + "'"

/** One column as it appears in `CREATE TABLE`: `"name" type [generated…|default …] [not null]`. */
internal fun pgColumnLine(row: Row): String {
    val dflt = row.str("dflt")
    val tail =
        when {
            row.text("generated") == "s" && dflt != null -> " GENERATED ALWAYS AS ($dflt) STORED"
            row.text("identity") == "a" -> " GENERATED ALWAYS AS IDENTITY"
            row.text("identity") == "d" -> " GENERATED BY DEFAULT AS IDENTITY"
            dflt != null -> " DEFAULT $dflt"
            else -> ""
        }
    return "${q(row.text("name"))} ${row.text("type")}$tail" + if (row.flag("notnull")) " NOT NULL" else ""
}

private fun constraintClause(row: Row) = "CONSTRAINT ${q(row.text("name"))} ${row.text("def")}"

/**
 * `CREATE TABLE` from columns and constraints, then `CREATE INDEX` for indexes backing no constraint
 * and triggers.
 */
internal fun pgTableDdl(
    schema: String,
    table: String,
    rows: PgSchemaRows,
): String {
    val lines =
        rows.columns.filter { it.text("tbl") == table }.map { pgColumnLine(it) } +
            rows.constraints.filter { it.text("tbl") == table }.map { constraintClause(it) }
    val create = "CREATE TABLE ${qualified(schema, table)} (\n" + lines.joinToString(",\n") { "    $it" } + "\n)"
    val indexes = rows.indexes.filter { it.text("tbl") == table && !it.flag("backs") }.map { it.text("def") }
    val triggers = rows.triggers.filter { it.text("tbl") == table }.map { it.text("def") }
    return (listOf(create) + indexes + triggers).joinToString("\n") { withSemicolon(it) }
}

/** The DDL of a column, key, index, check or trigger [obj] from the schema's rows; `null` for other kinds. */
internal fun pgTableChildDdl(
    obj: DbObject,
    rows: PgSchemaRows,
): String? {
    val table = obj.table ?: return null

    fun row(list: List<Row>) = list.firstOrNull { it.text("tbl") == table && it.text("name") == obj.name }
    return when (obj.kind) {
        ObjectKind.COLUMN -> {
            row(rows.columns)?.let {
                withSemicolon("ALTER TABLE ${qualified(obj.schema, table)} ADD COLUMN ${pgColumnLine(it)}")
            }
        }

        ObjectKind.PRIMARY_KEY, ObjectKind.UNIQUE, ObjectKind.FOREIGN_KEY, ObjectKind.CHECK -> {
            row(rows.constraints)?.let {
                withSemicolon("ALTER TABLE ${qualified(obj.schema, table)} ADD ${constraintClause(it)}")
            }
        }

        ObjectKind.INDEX -> {
            row(rows.indexes)?.let { withSemicolon(it.text("def")) }
        }

        ObjectKind.TRIGGER -> {
            row(rows.triggers)?.let { withSemicolon(it.text("def")) }
        }

        else -> {
            null
        }
    }
}

internal fun pgViewDdl(
    obj: DbObject,
    definition: String,
): String {
    val head =
        if (obj.kind == ObjectKind.MATERIALIZED_VIEW) "CREATE MATERIALIZED VIEW" else "CREATE OR REPLACE VIEW"
    val tail = if (obj.kind == ObjectKind.MATERIALIZED_VIEW) "\nWITH DATA" else ""
    return withSemicolon("$head ${qualified(obj.schema, obj.name)} AS\n${definition.trim().trimEnd(';')}$tail")
}

internal fun pgSequenceDdl(
    obj: DbObject,
    row: Row,
): String =
    withSemicolon(
        "CREATE SEQUENCE ${qualified(obj.schema, obj.name)}\n" +
            "    AS ${row.text("type")}\n" +
            "    START WITH ${row.text("start_value")}\n" +
            "    INCREMENT BY ${row.text("increment_by")}\n" +
            "    MINVALUE ${row.text("min_value")}\n" +
            "    MAXVALUE ${row.text("max_value")}\n" +
            "    CACHE ${row.text("cache_size")}\n" +
            "    " + if (row.flag("cycle")) "CYCLE" else "NO CYCLE",
    )

internal fun pgEnumDdl(
    obj: DbObject,
    labels: List<String>,
): String =
    withSemicolon(
        "CREATE TYPE ${qualified(obj.schema, obj.name)} AS ENUM (${labels.joinToString(", ") { literal(it) }})",
    )

internal fun pgDomainDdl(
    obj: DbObject,
    domain: Row?,
    constraints: List<Row>,
): String {
    val parts =
        buildList {
            add("CREATE DOMAIN ${qualified(obj.schema, obj.name)} AS ${domain?.text("base") ?: obj.detail}")
            domain?.str("dflt")?.let { add("DEFAULT $it") }
            if (domain?.flag("notnull") == true) add("NOT NULL")
            constraints.forEach { add(constraintClause(it)) }
        }
    return withSemicolon(parts.joinToString("\n    "))
}

internal fun pgCompositeDdl(
    obj: DbObject,
    attributes: List<Row>,
): String =
    withSemicolon(
        "CREATE TYPE ${qualified(obj.schema, obj.name)} AS (\n" +
            attributes.joinToString(",\n") { "    ${q(it.text("name"))} ${it.text("type")}" } + "\n)",
    )
